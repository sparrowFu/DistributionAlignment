_CAPTION_SYSTEM = (
    "You convert visual question-answer pairs into natural English declarative "
    "image-description sentences. Always output English. Every sentence MUST be "
    "grammatically correct and read like a fluent caption of what the image shows."
)

_CAPTION_USER = """Rewrite the following question-answer pair as ONE declarative sentence that DESCRIBES THE IMAGE. The answer must appear naturally inside the sentence.

Question: {QUESTION}
Answer: {ANSWER}
Answer type: {TYPE}   (one of: color | number | location | object)

Rules:
- Output ONLY the caption sentence. No quotes, no explanation, no extra text.
- Make it declarative and image-descriptive, not a question.
- GRAMMAR (important): the sentence MUST be grammatically correct, natural English. Fix word order, subject-verb agreement, articles (a/an/the), pluralization, and prepositions. You MAY reorder or lightly rephrase the question's words to achieve fluent grammar. Drop a leading "a"/"an" when the subject is plural (e.g. "carrots are ...", not "a carrots are ..."). For "how many" questions, prefer "there are <answer> ...".

Examples:
Q: what is the man holding a snowboard on top of a snow covered | A: hill | type: object
a man is holding a snowboard on top of a snow covered hill

Q: what are sitting on the counter in different stages of cutting with a knife | A: carrots | type: object
carrots are sitting on the counter in different stages of cutting with a knife

Q: what is the color of the bus | A: green | type: color
the color of the bus is green

Q: how many red motorcycles with riders in protective gear are on the street | A: three | type: number
there are three red motorcycles with riders in protective gear on the street

Q: where is the woman while her baby is sleeping | A: kitchen | type: location
the woman is in the kitchen while her baby is sleeping

Now convert:
Q: {QUESTION} | A: {ANSWER} | type: {TYPE}"""


class CaptionGenerator:
    """Call an OpenAI-compatible chat API to emit a final caption directly."""

    def __init__(self, api_key: str, base_url: str, model: str,
                 max_retries: int = 5, retry_wait: float = 5.0,
                 delay: float = 0.5, timeout: int = 60, max_tokens: int = 96):
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.max_retries = max_retries
        self.retry_wait = retry_wait
        self.delay = delay
        self.timeout = timeout
        self.max_tokens = max_tokens

    def _chat(self, messages: List[Dict]) -> str:
        url = self.base_url + "/chat/completions"
        body = json.dumps({
            "model": self.model,
            "messages": messages,
            "temperature": 0,
            "max_tokens": self.max_tokens,
        }).encode("utf-8")
        last_err = None
        for attempt in range(self.max_retries):
            try:
                req = urllib.request.Request(
                    url, data=body,
                    headers={"Authorization": f"Bearer {self.api_key}",
                             "Content-Type": "application/json"},
                    method="POST",
                )
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                return data["choices"][0]["message"]["content"].strip()
            except (urllib.error.URLError, urllib.error.HTTPError, OSError, KeyError, ValueError) as e:
                last_err = e
                wait = self.retry_wait * (attempt + 1)
                logger.warning(f"API call failed (attempt {attempt + 1}/{self.max_retries}): {e}; retry in {wait}s")
                time.sleep(wait)
        raise RuntimeError(f"API call failed after {self.max_retries} attempts: {last_err}")

    def generate(self, question: str, answer: str, qtype: int) -> str:
        # Use .replace (not .format) so any literal braces survive untouched.
        user = (_CAPTION_USER
                .replace("{QUESTION}", question)
                .replace("{ANSWER}", answer)
                .replace("{TYPE}", TYPE_NAMES.get(qtype, "object")))
        messages = [
            {"role": "system", "content": _CAPTION_SYSTEM},
            {"role": "user", "content": user},
        ]
        text = self._chat(messages)
        if self.delay:
            time.sleep(self.delay)
        # Keep only the last non-empty line (model may add a stray preamble); strip quotes.
        cand = [c.strip().strip('"').strip("'").strip() for c in text.splitlines() if c.strip()]
        caption = cand[-1] if cand else ""
        if not caption:
            logger.warning(f"Empty caption for Q={question!r} A={answer!r}; using answer as caption")
            caption = answer
        return caption


class LocalCaptionGenerator:
    """Generate captions with a local Hugging Face model loaded via transformers.

    Two model families, selected by `kind`:
      - "gemma": AutoProcessor + AutoModelForMultimodalLM (text-only generation)
      - "llama": AutoTokenizer  + AutoModelForCausalLM

    Loads model + (processor|tokenizer) ONCE. Reuses the SAME prompt templates and
    output post-processing as the API CaptionGenerator, so backends are
    interchangeable. Batched generation (left-padded) drives throughput via
    generate_batch(); generate()/generate_one() keep a single-sample path.
    """

    supports_batch = True
    # kind -> (processor class name, model class name) on the `transformers` module.
    _KIND_CLASSES = {
        "gemma": ("AutoProcessor", "AutoModelForMultimodalLM"),
        "llama": ("AutoTokenizer", "AutoModelForCausalLM"),
    }

    def __init__(self, kind: str = "gemma", model_path: str = "", dtype: str = "bf16",
                 device: str = "cuda", batch_size: int = 32, max_new_tokens: int = 96,
                 do_sample: bool = False, trust_remote_code: bool = False,
                 model_name: str = ""):
        import torch
        import transformers

        if kind not in self._KIND_CLASSES:
            raise ValueError(f"Unknown model kind {kind!r}; use 'gemma' or 'llama'.")
        if not model_path:
            raise ValueError("Local backend requires a model path: set "
                             "LLM_LOCAL_GEMMA_PATH/LLM_LOCAL_LLAMA_PATH in config.py "
                             "or pass --model-path.")
        model_dir = Path(model_path).expanduser()
        if not model_dir.exists():
            raise FileNotFoundError(f"Local model path not found: {model_dir}")

        dtype_map = {"bf16": torch.bfloat16, "fp16": torch.float16, "fp32": torch.float32}
        if dtype not in dtype_map:
            raise ValueError(f"dtype must be one of {list(dtype_map)}, got {dtype!r}")
        torch_dtype = dtype_map[dtype]

        # transformers 5.x renamed the from_pretrained kwarg torch_dtype -> dtype.
        major = int(transformers.__version__.split(".")[0])
        dtype_kw = "dtype" if major >= 5 else "torch_dtype"

        resolved_device = device
        if device == "auto":
            resolved_device = "cuda" if torch.cuda.is_available() else "cpu"

        self.kind = kind
        self.torch = torch
        self.batch_size = batch_size
        self.max_new_tokens = max_new_tokens
        self.do_sample = do_sample
        self.device = resolved_device
        self.model_name = model_name or model_dir.name

        logger.info(f"Loading local model [{kind}]: {model_dir} (dtype={dtype}, "
                    f"device={resolved_device}, batch={batch_size}, do_sample={do_sample})")
        self._load(model_dir, dtype_kw, torch_dtype, trust_remote_code, device)

        # Inner token-level handle (pad token, padding side, pad_token_id).
        # AutoTokenizer has no .tokenizer attr; AutoProcessor does.
        self.tokenizer = getattr(self.processor, "tokenizer", self.processor)
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
        # Left padding so every prompt ends at the same position for generation.
        self.tokenizer.padding_side = "left"

        if device != "auto":
            self.model = self.model.to(resolved_device)
        self.model.eval()
        logger.info(f"Local model ready: {self.model_name} ({kind}) on {resolved_device}")

    def _load(self, model_dir: Path, dtype_kw: str, torch_dtype, trust_remote_code: bool,
              device: str):
        """Load processor/tokenizer + model for the configured family."""
        import transformers
        proc_name, model_name = self._KIND_CLASSES[self.kind]
        proc_cls = getattr(transformers, proc_name)
        model_cls = getattr(transformers, model_name)
        self.processor = proc_cls.from_pretrained(
            str(model_dir), trust_remote_code=trust_remote_code)
        load_kwargs = {dtype_kw: torch_dtype, "trust_remote_code": trust_remote_code}
        if device == "auto":
            load_kwargs["device_map"] = "auto"   # requires accelerate
        self.model = model_cls.from_pretrained(str(model_dir), **load_kwargs)

    # -- prompt building ----
    def _messages(self, question: str, answer: str, qtype: int) -> List[Dict]:
        user = (_CAPTION_USER
                .replace("{QUESTION}", question)
                .replace("{ANSWER}", answer)
                .replace("{TYPE}", TYPE_NAMES.get(qtype, "object")))
        return [{"role": "system", "content": _CAPTION_SYSTEM},
                {"role": "user", "content": user}]

    def _raw_prompt(self, question: str, answer: str, qtype: int) -> str:
        msgs = self._messages(question, answer, qtype)
        return f"{msgs[0]['content']}\n\n{msgs[1]['content']}"

    def _to_prompt(self, question: str, answer: str, qtype: int) -> str:
        """Render the prompt for this model family.

        - gemma: the Gemma4Unified processor/tokenizer ships NO chat template and
          emits EOS immediately on a bare prompt, so wrap it in Gemma turn markers
          (`<start_of_turn>user ... <end_of_turn>\\n<start_of_turn>model\\n`).
        - llama: apply the chat template; fall back to a plain string for base
          models that ship no template.
        """
        raw = self._raw_prompt(question, answer, qtype)
        if self.kind == "gemma":
            return f"<start_of_turn>user\n{raw}<end_of_turn>\n<start_of_turn>model\n"
        try:
            return self.processor.apply_chat_template(
                self._messages(question, answer, qtype),
                tokenize=False, add_generation_prompt=True)
        except Exception:
            return raw

    @staticmethod
    def _decode_caption(text: str) -> str:
        # Keep only the last non-empty line; strip surrounding quotes (same as API).
        cand = [c.strip().strip('"').strip("'").strip()
                for c in text.splitlines() if c.strip()]
        return cand[-1] if cand else ""

    def _extract_caption(self, text: str) -> str:
        """Pull the caption out of the model's raw output.

        Local models emit the caption first, then often keep going (Gemma
        hallucinates another turn; a base Llama generates more few-shot examples).
        Cut Gemma at its turn marker, then take the FIRST non-empty line. Reject
        lines that look like hallucinated few-shot example headers ('Q: ...' or
        '... | A: ... | type: ...') so a base model degrades to the answer rather
        than emitting garbage.
        """
        if self.kind == "gemma":
            text = text.split("<end_of_turn>")[0]
        cand = [c.strip().strip('"').strip("'").strip()
                for c in text.splitlines() if c.strip()]
        cap = cand[0] if cand else ""
        low = cap.lower()
        if low[:2] == "q:" or " | a:" in low or "| type:" in low:
            return ""
        return cap

    def generate(self, question: str, answer: str, qtype: int) -> str:
        """Single-sample interface shared with the API CaptionGenerator."""
        return self.generate_one(question, answer, qtype)

    def generate_one(self, question: str, answer: str, qtype: int) -> str:
        return self.generate_batch([(question, answer, qtype)])[0]

    def generate_batch(self, items: List[Tuple[str, str, int]]) -> List[str]:
        """One forward pass over `items`. The caller chunks by self.batch_size.

        items: list of (question, answer, qtype). Returns one caption per item.
        """
        torch = self.torch
        prompts = [self._to_prompt(q, a, t) for q, a, t in items]
        enc = self._encode(prompts)
        input_len = enc["input_ids"].shape[1]
        enc = {k: v.to(self.device) for k, v in enc.items()}
        gen_kwargs = dict(max_new_tokens=self.max_new_tokens,
                          do_sample=self.do_sample,
                          pad_token_id=self.tokenizer.pad_token_id)
        if self.kind == "gemma":
            # Stop at the turn marker so Gemma doesn't keep generating another turn.
            gen_kwargs["stop_strings"] = ["<end_of_turn>"]
            gen_kwargs["tokenizer"] = self.tokenizer
        with torch.no_grad():
            out = self.model.generate(**enc, **gen_kwargs)
        gen = out[:, input_len:]                      # drop the padded prompt
        texts = self._batch_decode(gen)
        captions = [self._extract_caption(t) for t in texts]
        # Fall back to the answer if the model emitted nothing usable.
        return [c if c else a for c, (_, a, _) in zip(captions, items)]

    # -- tokenization + decoding --------------------------------------------
    def _encode(self, prompts: List[str]) -> Dict:
        """Tokenize a batch of prompts. AutoProcessor wants text= (and may reject
        a plain list); AutoTokenizer takes a positional list. If the Gemma
        processor refuses a text-only batch, fall back to its inner tokenizer."""
        if self.kind == "gemma":
            try:
                return self.processor(text=prompts, return_tensors="pt",
                                      padding=True, truncation=True)
            except Exception as e:
                logger.warning(f"Gemma processor text-encode failed ({e}); "
                               f"falling back to its tokenizer")
        return self.tokenizer(prompts, return_tensors="pt", padding=True, truncation=True)

    def _batch_decode(self, token_ids) -> List[str]:
        fn = getattr(self.processor, "batch_decode", None) or self.tokenizer.batch_decode
        return fn(token_ids, skip_special_tokens=True)


def load_api_config(path: Path) -> Dict:
    """Load api_config.json: {provider: {api_key, base_url, models: {alias: id}}}.

    Top-level keys starting with '_' (e.g. '_readme') are ignored, so the file can
    carry documentation. See api_config.example.json for the schema.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"api_config not found: {path}\nCopy api_config.example.json to "
            f"{path.name} and fill in your key (it is gitignored).")
    return json.loads(path.read_text(encoding="utf-8"))


def resolve_provider(cfg: Dict, provider: str) -> Dict:
    """Return the provider block for `provider`."""
    available = [k for k in cfg if not k.startswith("_") and isinstance(cfg[k], dict)]
    prov = cfg.get(provider)
    if not isinstance(prov, dict):
        raise ValueError(f"Provider '{provider}' not in api_config. Available: {available}")
    if not prov.get("api_key") or not prov.get("base_url"):
        raise ValueError(f"Provider '{provider}' must define 'api_key' and 'base_url'")
    return prov


def make_api_generator(args) -> CaptionGenerator:
    cfg = load_api_config(Path(args.api_config))
    prov = resolve_provider(cfg, args.provider)
    models = prov.get("models") or {}
    model_id = models.get(args.model)
    if model_id is None:
        # Treat --model as a raw model id if it is not a known alias.
        model_id = args.model
        logger.warning(f"Model alias '{args.model}' not in provider '{args.provider}' "
                       f"models map (have {list(models)}); using it as a raw model id")
    logger.info(f"Using API caption generator: provider={args.provider} "
                f"model={args.model} ({model_id}) base_url={prov['base_url']}")
    return CaptionGenerator(
        api_key=prov["api_key"], base_url=prov["base_url"], model=model_id,
        max_retries=config.LLM_API_MAX_RETRIES, retry_wait=config.LLM_API_RETRY_WAIT,
        delay=config.LLM_API_DELAY, timeout=config.LLM_API_TIMEOUT,
    )


def make_local_generator(args) -> "LocalCaptionGenerator":
    kind = args.model_kind or config.LLM_LOCAL_MODEL_KIND
    default_path = {"gemma": config.LLM_LOCAL_GEMMA_PATH,
                    "llama": config.LLM_LOCAL_LLAMA_PATH}.get(kind, "")
    model_path = args.model_path or config.LLM_LOCAL_MODEL_PATH or default_path
    dtype = args.dtype or config.LLM_LOCAL_DTYPE
    device = args.device or config.LLM_LOCAL_DEVICE
    return LocalCaptionGenerator(
        kind=kind,
        model_path=model_path,
        dtype=dtype,
        device=device,
        batch_size=args.batch_size,
        max_new_tokens=config.LLM_LOCAL_MAX_NEW_TOKENS,
        do_sample=config.LLM_LOCAL_DO_SAMPLE,
        trust_remote_code=config.LLM_LOCAL_TRUST_REMOTE_CODE,
        model_name=config.LLM_LOCAL_MODEL_NAME,
    )


def make_generator(args):
    """Dispatch to the local (transformers) or api (HTTP) backend."""
    backend = args.backend
    if backend == "local":
        return make_local_generator(args)
    if backend == "api":
        return make_api_generator(args)
    raise ValueError(f"Unknown --backend {backend!r}; use 'local' or 'api'.")


