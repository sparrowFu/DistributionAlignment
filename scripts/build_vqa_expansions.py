def caption_cache_key(question: str, answer: str) -> str:
    return f"{question}\t{answer}"


def build_entry(filename: str, qtype: int, question: str, answer: str, caption: str) -> Dict:
    return {
        "imagefilename": filename,
        "imagepath": image_relpath(filename),
        "type": qtype,
        "question": question,
        "answer": answer,
        "caption": caption,
    }


def _fs_safe(name: str) -> str:
    """Filesystem-safe token: keep alnum / '-' / '.' / '_', replace the rest."""
    return "".join(c if (c.isalnum() or c in "-_.") else "_" for c in name) or "model"


def derive_model_tag(generator) -> str:
    """Short tag identifying the model, used in output filenames:
        {split}_{tag}_captions.jsonl
        {split}_{tag}_expansions.jsonl / .json

    Local backend -> the model dir basename (e.g. 'gemma' / 'llama').
    API backend   -> the resolved model id (sanitized).
    Different models get separate files because they emit different captions for
    the same (question, answer) pair.
    """
    name = getattr(generator, "model_name", "") or getattr(generator, "model", "") or "model"
    return _fs_safe(name)


def load_caption_cache(path: Path) -> Dict[str, str]:
    """Return {question+answer -> caption} cache."""
    cache: Dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
                cache[rec["key"]] = rec["caption"]
            except (json.JSONDecodeError, KeyError):
                continue
    return cache


def count_lines(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for line in path.read_text(encoding="utf-8").splitlines() if line.strip())


def consolidate(jsonl_path: Path, json_path: Path) -> int:
    entries = []
    for line in jsonl_path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            entries.append(json.loads(line))
    json_path.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8")
    return len(entries)


