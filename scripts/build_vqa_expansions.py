"""
Build a VQA-as-retrieval expansion dataset (local or API caption generation).

For each VQA sample, call an OpenAI-compatible chat API (SiliconFlow) to turn the
(question, answer) pair into a single grammatical, natural-English declarative
caption that describes the image. No templates, no placeholders, no regex -- the
LLM emits the final caption directly.

Output JSON (one entry per sample), written to
    outputs/vqa_expansions/{split}_{tag}_expansions.json
    [
      {
        "imagefilename": "000000397899.jpg",
        "imagepath": "TrainDatasets/mscoco_captions/images/000000397899.jpg",
        "type": 0,
        "question": "...",
        "answer": "...",
        "caption": "<declarative English sentence>"
      },
      ...
    ]

{tag} is a tag identifying the model (e.g. 'gemma', 'llama'); each model writes
its own {split}_{tag}_captions.jsonl / _expansions.jsonl / .json so captions
from different models never collide.

Resumable: streams entries to a .jsonl (one per line), caches generated captions
to {split}_{tag}_captions.jsonl (keyed by question+answer, so identical Q/A
pairs across images reuse one generation), and consolidates to the final
{split}_{tag}_expansions.json array at the end.

    # LOCAL backend (default): transformers. Two families, paths from config.py:
    #   gemma -> AutoProcessor + AutoModelForMultimodalLM
    #   llama -> AutoTokenizer  + AutoModelForCausalLM
    # quick local dry run (3 samples, start fresh), one-at-a-time for debugging
    # tune throughput / precision / explicit path

    # API backend (original HTTP path): provider/model aliases in the api config file

Local backend settings all have CLI overrides:
--backend --model-kind --model-path --batch-size --dtype --device --no-batch.
The dedup cache ({split}_captions.jsonl) and resume logic are shared by both
backends, so captions already generated by either are reused.

API credentials live in the api config file (gitignored; an example template ships alongside it). Add more providers or models there -- select them with --provider/--model.
"""

